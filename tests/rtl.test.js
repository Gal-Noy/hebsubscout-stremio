'use strict';
const assert = require('node:assert/strict');
const { fixSubtitleRtl } = require('../lib/rtl');
const R = '\u202B', P = '\u202C';
const input = '1\r\n00:00:01,000 --> 00:00:04,000\r\nמה נשמע?\r\nHello, שלום!\r\n\r\n2\r\n00:00:05,000 --> 00:00:06,000\r\nEnglish only.\r\n';
const expected = `1\r\n00:00:01,000 --> 00:00:04,000\r\n${R}מה נשמע?${P}\r\n${R}Hello, שלום!${P}\r\n\r\n2\r\n00:00:05,000 --> 00:00:06,000\r\nEnglish only.\r\n`;
assert.equal(fixSubtitleRtl(input), expected, 'Preserve timecodes and CRLF');
assert.equal(fixSubtitleRtl(expected), expected, 'Idempotent');
assert.equal(fixSubtitleRtl('1\n00:00:01,000 --> 00:00:02,000\n?שלום\n'), `1\n00:00:01,000 --> 00:00:02,000\n${R}?שלום${P}\n`, 'Do not reorder punctuation');
assert.equal(fixSubtitleRtl('1\n00:00:01,000 --> 00:00:02,000\n\u200Fשלום?\n'), '1\n00:00:01,000 --> 00:00:02,000\n\u200Fשלום?\n', 'Respect existing RLM');
assert.equal(fixSubtitleRtl('1\n00:00:01,000 --> 00:00:02,000\n\u2067שלום?\u2069\n'), '1\n00:00:01,000 --> 00:00:02,000\n\u2067שלום?\u2069\n', 'Respect existing isolates');
assert.equal(fixSubtitleRtl('WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nשלום\n'), 'WEBVTT\n\n00:00:01.000 --> 00:00:03.000\nשלום\n', 'Leave WebVTT untouched');
console.log('RTL tests passed (6 assertions)');
